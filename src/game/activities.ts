/** Three questions for the day: a proverb, a riddle and a custom, different each day. */
function wisdomFor(day: number): Step[] {
  const at = <T,>(list: T[], k: number) => list[(day * k + 1) % list.length];
  return [at(PROVERBS, 3), at(RIDDLES, 1), at(CUSTOMS, 5)];
}

